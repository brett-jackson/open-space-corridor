#!/usr/bin/env python3
"""Save every space's iNaturalist place boundary to js/boundaries.js for the landing page map.

Boundaries rarely change, so run this when you add a space or change its place_id:

    python3 scripts/update_boundaries.py

All places are fetched in one request. Coordinates are rounded to 6 decimals (~10 cm).
"""
import json
import re
import urllib.request
from pathlib import Path

API = "https://api.inaturalist.org/v1/places/"
USER_AGENT = "open-space-corridor boundaries (iNaturalist user: brettjackson)"
ROOT = Path(__file__).resolve().parent.parent
SPACES_JS = ROOT / "js" / "spaces.js"
OUT = ROOT / "js" / "boundaries.js"


def read_spaces():
    match = re.search(r"=\s*(\[.*\])\s*;?\s*$", SPACES_JS.read_text(), re.S)
    if not match:
        raise SystemExit(f"couldn't find the SPACES list in {SPACES_JS}")
    return json.loads(match.group(1))


def rounded(coords):
    if isinstance(coords, (int, float)):
        return round(coords, 6)
    return [rounded(c) for c in coords]


def main():
    spaces = [spc for spc in read_spaces() if spc.get("place_id")]
    ids = ",".join(str(spc["place_id"]) for spc in spaces)
    req = urllib.request.Request(API + ids, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        places = {p["id"]: p for p in json.load(resp)["results"]}

    boundaries = {}
    for spc in spaces:
        geometry = (places.get(spc["place_id"]) or {}).get("geometry_geojson")
        if not geometry:
            print(f"{spc['id']}: no boundary on iNaturalist (place {spc['place_id']}); skipping")
            continue
        boundaries[spc["id"]] = {"type": geometry["type"], "coordinates": rounded(geometry["coordinates"])}
        print(f"{spc['id']}: {geometry['type']}")

    OUT.write_text(
        "// Generated by scripts/update_boundaries.py from iNaturalist place geometries; space id -> GeoJSON\n"
        "window.SPACE_BOUNDARIES = " + json.dumps(boundaries, separators=(",", ":")) + ";\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
