#!/usr/bin/env python3
"""Save every space's boundary to js/boundaries.js for the landing page map.

Place spaces use their iNaturalist place geometry; bounding-box spaces are drawn as their
box, with any excluded boxes cut out as holes.

Boundaries rarely change, so run this when you add a space or change its place_id:

    python3 scripts/update_boundaries.py

All places are fetched in one request. Coordinates are rounded to 6 decimals (~10 cm).
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # for areas.py, even under python -I
from areas import API_V1, ROOT, box_params, exclusions, inat_get, read_spaces  # noqa: E402

USER_AGENT = "open-space-corridor boundaries (iNaturalist user: brettjackson)"
OUT = ROOT / "js" / "boundaries.js"


def rounded(coords):
    if isinstance(coords, (int, float)):
        return round(coords, 6)
    return [rounded(c) for c in coords]


def ring(box, clockwise=False):
    """A closed GeoJSON ring around a box; outer rings run counterclockwise, holes clockwise."""
    pts = [[box["swlng"], box["swlat"]], [box["nelng"], box["swlat"]], [box["nelng"], box["nelat"]], [box["swlng"], box["nelat"]]]
    if clockwise:
        pts.reverse()
    return pts + [pts[0]]


def box_geometry(space):
    outer = box_params(space["bbox"])
    holes = []
    for b in exclusions(space):
        clipped = {"nelat": min(b["nelat"], outer["nelat"]), "nelng": min(b["nelng"], outer["nelng"]),
                   "swlat": max(b["swlat"], outer["swlat"]), "swlng": max(b["swlng"], outer["swlng"])}
        if clipped["nelat"] > clipped["swlat"] and clipped["nelng"] > clipped["swlng"]:
            holes.append(ring(clipped, clockwise=True))
    return {"type": "Polygon", "coordinates": rounded([ring(outer)] + holes)}


def main():
    all_spaces = read_spaces()
    boundaries = {}
    for spc in all_spaces:
        if spc.get("bbox"):
            boundaries[spc["id"]] = box_geometry(spc)
            print(f"{spc['id']}: box with {len(boundaries[spc['id']]['coordinates']) - 1} excluded area(s)")

    spaces = [spc for spc in all_spaces if spc.get("place_id") and not spc.get("bbox")]
    places = {}
    if spaces:
        ids = ",".join(str(spc["place_id"]) for spc in spaces)
        places = {p["id"]: p for p in inat_get(API_V1 + "places/" + ids, USER_AGENT, {})["results"]}

    for spc in spaces:
        geometry = (places.get(spc["place_id"]) or {}).get("geometry_geojson")
        if not geometry:
            print(f"{spc['id']}: no boundary on iNaturalist (place {spc['place_id']}); skipping")
            continue
        boundaries[spc["id"]] = {"type": geometry["type"], "coordinates": rounded(geometry["coordinates"])}
        print(f"{spc['id']}: {geometry['type']}")

    boundaries = {spc["id"]: boundaries[spc["id"]] for spc in all_spaces if spc["id"] in boundaries}  # site order
    OUT.write_text(
        "// Generated by scripts/update_boundaries.py from iNaturalist places and spaces.js boxes; space id -> GeoJSON\n"
        "window.SPACE_BOUNDARIES = " + json.dumps(boundaries, separators=(",", ":")) + ";\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
