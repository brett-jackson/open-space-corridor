#!/usr/bin/env python3
"""Refresh each space's trends_cache.js with cumulative yearly counts from iNaturalist.

Each value is the running total as of December 31 of that year: all observations, and
the number of distinct species and observers seen so far (which can't be summed from
per-year counts, since the same species or person recurs). Only completed years are
cached; the site fetches the current year live. By default
just the years missing from a cache are requested, plus the most recent cached year
(late uploads and new IDs keep nudging it for a while).

    python3 scripts/update_trends_cache.py                  # every space
    python3 scripts/update_trends_cache.py broomfield       # just these spaces
    python3 scripts/update_trends_cache.py --refresh-years 3  # also re-fetch the last 3 cached years
    python3 scripts/update_trends_cache.py --full           # rebuild from scratch
"""
import argparse
import datetime
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.inaturalist.org/v2/"
USER_AGENT = "open-space-corridor trends cache (iNaturalist user: brettjackson)"
MIN_INTERVAL = 1.0  # iNaturalist asks for about 1 request per second
SPACES_DIR = Path(__file__).resolve().parent.parent / "spaces"

_last_request = 0.0


def inat(path, **params):
    global _last_request
    wait = _last_request + MIN_INTERVAL - time.time()
    if wait > 0:
        time.sleep(wait)
    _last_request = time.time()
    url = API + path + "?" + urllib.parse.urlencode({"verifiable": "true", **params})
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def read_place_id(space_dir):
    match = re.search(r"PLACE_ID\s*=\s*(\d+)", (space_dir / "constants.js").read_text())
    if not match:
        raise ValueError(f"no PLACE_ID in {space_dir / 'constants.js'}")
    return int(match.group(1))


def read_cache(path):
    if not path.exists():
        return None
    match = re.search(r"=\s*(\{.*\})\s*;?\s*$", path.read_text(), re.S)
    return json.loads(match.group(1)) if match else None


def write_cache(path, cache):
    body = json.dumps(cache, indent=2, sort_keys=True)
    path.write_text(
        "// Generated by scripts/update_trends_cache.py; cumulative totals at each year's end; the site fetches the current year live\n"
        f"const TRENDS_CACHE = {body};\n"
    )


def update_space(space_dir, full, refresh_years):
    place_id = read_place_id(space_dir)
    cache_path = space_dir / "trends_cache.js"
    old = None if full else read_cache(cache_path)
    if old and old.get("place_id") != place_id:
        print(f"  PLACE_ID changed ({old.get('place_id')} -> {place_id}); rebuilding")
        old = None
    if old and not old.get("cumulative"):
        print("  cache is in the old per-year format; rebuilding")
        old = None
    this_year = datetime.date.today().year

    # Observations: one histogram request covers every year; the running sum is cumulative
    hist = inat("observations/histogram", place_id=place_id, interval="year", date_field="observed")
    per_year = {int(d[:4]): n for d, n in hist["results"]["year"].items() if int(d[:4]) < this_year}
    if not per_year:
        print("  no completed years with observations; skipping")
        return
    years = list(range(min(per_year), this_year))
    observations, total = {}, 0
    for y in years:
        total += per_year.get(y, 0)
        observations[y] = total

    cache = {
        "place_id": place_id,
        "updated": datetime.date.today().isoformat(),
        "cumulative": True,
        "observations": {str(y): observations.get(y, 0) for y in years},
    }
    cached_years = sorted(int(y) for y in (old or {}).get("species", {}))
    stale = set(cached_years[-refresh_years:]) if refresh_years > 0 else set()

    # Species and observers: distinct count observed up to each year's end, skipping cached years
    for metric, path in (("species", "observations/species_counts"), ("observers", "observations/observers")):
        previous = (old or {}).get(metric, {})
        counts = {}
        for y in years:
            if str(y) in previous and y not in stale:
                counts[str(y)] = previous[str(y)]
                continue
            counts[str(y)] = inat(path, place_id=place_id, d2=f"{y}-12-31", per_page=0)["total_results"]
            print(f"  {metric} {y}: {counts[str(y)]}")
        cache[metric] = counts

    write_cache(cache_path, cache)
    print(f"  wrote {cache_path.relative_to(SPACES_DIR.parent)} ({years[0]}-{years[-1]})")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spaces", nargs="*", help="space folder names (default: all)")
    parser.add_argument("--full", action="store_true", help="ignore existing caches and refetch every year")
    parser.add_argument("--refresh-years", type=int, default=1, help="re-fetch this many of the latest cached years (default 1)")
    args = parser.parse_args()

    names = args.spaces or sorted(p.name for p in SPACES_DIR.iterdir() if (p / "constants.js").exists())
    for name in names:
        print(name)
        try:
            update_space(SPACES_DIR / name, args.full, args.refresh_years)
        except Exception as err:  # keep going so one bad space doesn't block the rest
            print(f"  failed: {err}", file=sys.stderr)


if __name__ == "__main__":
    main()
