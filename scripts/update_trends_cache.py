#!/usr/bin/env python3
"""Refresh each space's trends_cache.js with cumulative monthly counts from iNaturalist.

Each value is the running total as of the last day of that month ("YYYY-MM"): all
observations, and the number of distinct species and observers seen so far. Only completed
months are cached; the site adds today's totals live.

Every month is computed from one download of the space's observations (200 per request, so
a few requests per space), which is far cheaper than a distinct-count query per month and
also picks up late uploads and new IDs in every month. Species are counted the way
iNaturalist's species_counts does (leaf taxa: observed taxa with no observed descendant), so
the cache lines up with the live total; spaces with exclusions count species-level taxa
instead, matching js/area.js, which computes their live totals the same way.

    python3 scripts/update_trends_cache.py                  # every space
    python3 scripts/update_trends_cache.py broomfield       # just these spaces
    python3 scripts/update_trends_cache.py --if-missing     # only spaces missing the last completed month
    python3 scripts/update_trends_cache.py markel --bbox 39.9461,-105.0613,39.9452,-105.0619
        # stand-in for a place iNaturalist hasn't indexed yet: count a bounding box instead
        # (nelat,nelng,swlat,swlng); the next normal run replaces it once the place has data
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # for areas.py, even under python -I
from areas import ROOT, all_observations, area_key, area_params, exclusions, read_js_object, read_spaces  # noqa: E402

USER_AGENT = "open-space-corridor trends cache (iNaturalist user: brettjackson)"
SPACES_DIR = ROOT / "spaces"


def write_cache(path, cache):
    """Write the cache, unless only its "updated" date would change (keeps scheduled runs quiet)."""
    old = read_js_object(path)
    if old and {k: v for k, v in old.items() if k != "updated"} == {k: v for k, v in cache.items() if k != "updated"}:
        return False
    body = json.dumps(cache, indent=2, sort_keys=True)
    path.write_text(
        "// Generated by scripts/update_trends_cache.py; cumulative totals at each month's end; the site adds today's totals live\n"
        f"const TRENDS_CACHE = {body};\n"
    )
    return True


def months_between(first, last):
    """"YYYY-MM" strings from first to last, inclusive."""
    y, m = int(first[:4]), int(first[5:7])
    out = []
    while f"{y:04d}-{m:02d}" <= last:
        out.append(f"{y:04d}-{m:02d}")
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


def monthly_totals(observations, last_month, leaf_species):
    """Month-end running totals of observations, species and observers, through last_month."""
    dated = sorted((o for o in observations if o.get("observed_on")), key=lambda o: o["observed_on"])
    dated = [o for o in dated if o["observed_on"][:7] <= last_month]
    totals = {"observations": {}, "species": {}, "observers": {}}
    if not dated:
        return totals
    taxa, ancestors, users = set(), set(), set()
    species, i = 0, 0
    for month in months_between(dated[0]["observed_on"][:7], last_month):
        while i < len(dated) and dated[i]["observed_on"][:7] <= month:
            taxon = dated[i].get("taxon") or {}
            if leaf_species and taxon.get("id") and taxon["id"] not in taxa:
                # A leaf is an observed taxon that no other observed taxon descends from
                taxa.add(taxon["id"])
                species += taxon["id"] not in ancestors
                for a in taxon.get("ancestor_ids") or []:
                    if a != taxon["id"] and a not in ancestors:
                        ancestors.add(a)
                        species -= a in taxa
            elif not leaf_species and taxon.get("rank_level", 100) <= 10:  # species-level, matching js/area.js
                taxa.add(taxon["id"])
                species = len(taxa)
            if (dated[i].get("user") or {}).get("login"):
                users.add(dated[i]["user"]["login"])
            i += 1
        totals["observations"][month] = i
        totals["species"][month] = species
        totals["observers"][month] = len(users)
    return totals


def update_space(space, if_missing, bbox=None):
    space_dir = SPACES_DIR / space["id"]
    space_dir.mkdir(exist_ok=True)
    cache_path = space_dir / "trends_cache.js"
    today = datetime.date.today()
    last_month = (today.replace(day=1) - datetime.timedelta(days=1)).strftime("%Y-%m")

    old = read_js_object(cache_path)
    if if_missing and not bbox and old and old.get("interval") == "month" and old.get("area_key") == area_key(space) \
            and not old.get("bbox") and last_month in old.get("observations", {}):
        print("  up to date")
        return

    area = bbox or area_params(space)
    totals = monthly_totals(all_observations(space, USER_AGENT, area), last_month, leaf_species=not exclusions(space))
    if not totals["observations"]:
        print("  no completed months with observations; skipping (any existing cache is left as is)")
        return
    cache = {"place_id": space.get("place_id"), "area_key": area_key(space), "updated": today.isoformat(),
             "cumulative": True, "interval": "month", **totals}
    if bbox:
        cache["bbox"] = bbox  # the site counts this same box live
    months = list(totals["observations"])
    if write_cache(cache_path, cache):
        print(f"  wrote {cache_path.relative_to(SPACES_DIR.parent)} ({months[0]} to {months[-1]})")
    else:
        print("  unchanged")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spaces", nargs="*", help="space ids from js/spaces.js (default: all)")
    parser.add_argument("--if-missing", action="store_true", help="skip spaces whose cache already has the last completed month")
    parser.add_argument("--bbox", help="nelat,nelng,swlat,swlng to count instead of the place (one space only)")
    args = parser.parse_args()

    bbox = None
    if args.bbox:
        if len(args.spaces) != 1:
            parser.error("--bbox needs exactly one space id")
        bbox = dict(zip(("nelat", "nelng", "swlat", "swlng"), (float(v) for v in args.bbox.split(","))))
        if len(bbox) != 4:
            parser.error("--bbox is nelat,nelng,swlat,swlng")

    spaces = {spc["id"]: spc for spc in read_spaces()}
    names = args.spaces or list(spaces)
    for name in names:
        print(name)
        if name not in spaces:
            print("  not in js/spaces.js; skipping", file=sys.stderr)
            continue
        try:
            update_space(spaces[name], args.if_missing, bbox)
        except Exception as err:  # keep going so one bad space doesn't block the rest
            print(f"  failed: {err}", file=sys.stderr)


if __name__ == "__main__":
    main()
